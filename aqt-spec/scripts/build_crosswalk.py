#!/usr/bin/env python3
"""Check the GxP catalogues and generate ``crosswalk.md`` and ``catalogues/catalogues.json``.

Needs PyYAML (``pip install pyyaml``; part of the ``test`` extra). The JSON
output is packaged with the library so tools can cite catalogue IDs with the
standard library only (``aqt_evidence.catalogues``).

Usage: ``python scripts/build_crosswalk.py [--check]``
"""

from __future__ import annotations

import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
CATALOGUES = ROOT / "catalogues"
ORDER = ["alcoa", "annex11-2011", "annex11-2025d", "part11", "ch4-2025d", "annex22-2025d", "gdp-2013",
         "iso9001-2015", "euaiact", "ichq10", "ichq9"]
STATEMENT = ("Agent Quality Toolkit supports quality-management practices; it is not a validated system and does "
             "not by itself make any process compliant with GMP, GDP, 21 CFR Part 11 or EU Annex 11.")
MAX_PARAPHRASE = 400


def load() -> tuple[dict, list[dict], list[str]]:
    problems: list[str] = []
    features = yaml.safe_load((CATALOGUES / "features.yaml").read_text(encoding="utf-8"))["features"]
    registry = json.loads((ROOT / "schemas" / "registry.json").read_text(encoding="utf-8"))["types"]
    for name, feature in features.items():
        for record_type in feature.get("records", []):
            if record_type != "*" and record_type not in registry:
                problems.append(f"feature {name}: unknown record type {record_type}")
    catalogues, seen = [], set()
    files = {path.stem: path for path in CATALOGUES.glob("*.yaml") if path.stem != "features"}
    if sorted(files) != sorted(ORDER):
        problems.append(f"catalogue files {sorted(files)} differ from the published list {ORDER}")
    used = set()
    for name in ORDER:
        if name not in files:
            continue
        catalogue = yaml.safe_load(files[name].read_text(encoding="utf-8"))
        if catalogue.get("catalogue") != name:
            problems.append(f"{files[name].name}: catalogue must be {name!r}")
        for key in ("document", "version", "status", "consulted", "basis"):
            if not catalogue.get("source", {}).get(key):
                problems.append(f"{name}: source.{key} missing")
        for item in catalogue.get("items", []):
            item_id = item.get("id", "?")
            if not str(item_id).startswith(f"{name}:"):
                problems.append(f"{item_id}: id must start with {name}:")
            if item_id in seen:
                problems.append(f"{item_id}: duplicate id")
            seen.add(item_id)
            for key in ("clause", "title", "paraphrase"):
                if not item.get(key):
                    problems.append(f"{item_id}: {key} missing")
            if not isinstance(item.get("verified"), bool):
                problems.append(f"{item_id}: verified must be true or false")
            elif not item["verified"] and not item.get("note"):
                problems.append(f"{item_id}: an unverified item needs a note")
            paraphrase = item.get("paraphrase", "")
            if len(paraphrase) > MAX_PARAPHRASE or len(re.findall(r"[.!?](\s|$)", paraphrase)) > 2:
                problems.append(f"{item_id}: paraphrase longer than two sentences / {MAX_PARAPHRASE} characters")
            for feature in item.setdefault("supported_by", []):
                used.add(feature)
                if feature not in features:
                    problems.append(f"{item_id}: unknown feature {feature}")
            item.setdefault("user_must", "")
        catalogues.append(catalogue)
    for name in sorted(set(features) - used):
        problems.append(f"feature {name} is not cited by any catalogue item")
    return features, catalogues, problems


def records_for(features: dict, names: list[str]) -> list[str]:
    out: list[str] = []
    for name in names:
        for record_type in features[name].get("records", []):
            label = "any record" if record_type == "*" else record_type
            if label not in out:
                out.append(label)
    return out


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_markdown(features: dict, catalogues: list[dict]) -> str:
    lines = [
        "# GxP crosswalk",
        "",
        "Generated by `scripts/build_crosswalk.py` from `catalogues/*.yaml` — do not edit by hand.",
        "Licence: CC BY 4.0. Requirements are paraphrased in our own words with clause numbers; read the source "
        "documents for the binding text.",
        "",
        f"> {STATEMENT}",
        "",
        "**How to read it.** *Supported by* names AQT features that produce evidence or controls relevant to the "
        "clause; it never means the clause is met. *Evidence* lists the record types those features write. "
        "*You still must* lists duties that stay with the user (procedures, training, validation, administration). "
        "An empty *Supported by* means AQT does not help with this clause.",
        "",
        "## Contents",
        "",
    ]
    for catalogue in catalogues:
        anchor = re.sub(r"[^a-z0-9 -]", "", catalogue["title"].lower()).replace(" ", "-")
        lines.append(f"- [{catalogue['title']}](#{anchor}) — {len(catalogue['items'])} items")
    lines += ["- [AQT features](#aqt-features)", ""]
    for catalogue in catalogues:
        source = catalogue["source"]
        lines += [
            f"## {catalogue['title']}", "",
            f"Source: {source['document']} — {source['version']} ({source['status']}). Consulted {source['consulted']}.",
            f"Basis: {source['basis']}", "",
            "| ID | Requirement (paraphrase) | Supported by | Evidence | You still must |",
            "|---|---|---|---|---|",
        ]
        for item in catalogue["items"]:
            supported = ", ".join(f"`{f}`" for f in item["supported_by"]) or "—"
            evidence = ", ".join(f"`{r}`" if r != "any record" else r
                                 for r in records_for(features, item["supported_by"])) or "—"
            unverified = "" if item["verified"] else f" *Not verified against the source: {cell(item['note'])}*"
            lines.append(f"| `{item['id']}` | **{cell(item['title'])}.** {cell(item['paraphrase'])}{unverified} | {supported} | "
                         f"{evidence} | {cell(item['user_must']) or '—'} |")
        lines.append("")
    citations: dict[str, list[str]] = {name: [] for name in features}
    for catalogue in catalogues:
        for item in catalogue["items"]:
            for feature in item["supported_by"]:
                citations[feature].append(item["id"])
    lines += ["## AQT features", "", "| Feature | Package | What it does | Records | Cited by |", "|---|---|---|---|---|"]
    for name, feature in features.items():
        records = ", ".join("any record" if r == "*" else f"`{r}`" for r in feature.get("records", [])) or "—"
        lines.append(f"| `{name}` | {feature['package']} | {cell(feature['description'])} | {records} | "
                     f"{len(citations[name])} |")
    lines.append("")
    return "\n".join(lines)


def render_json(features: dict, catalogues: list[dict]) -> str:
    data = {"aqt_catalogues": "0.1", "statement": STATEMENT, "features": features,
            "catalogues": [{key: catalogue[key] for key in ("catalogue", "title", "licence", "source", "items")}
                           for catalogue in catalogues]}
    return json.dumps(data, indent=1, ensure_ascii=False, sort_keys=False) + "\n"


def main(argv: list[str]) -> int:
    features, catalogues, problems = load()
    for problem in problems:
        print("problem:", problem)
    if problems:
        return 1
    outputs = {ROOT / "crosswalk.md": render_markdown(features, catalogues),
               CATALOGUES / "catalogues.json": render_json(features, catalogues)}
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, text in outputs.items() if not p.exists() or p.read_text() != text]
        for item in stale:
            print("out of date:", item)
        return 1 if stale else 0
    for path, text in outputs.items():
        path.write_text(text, encoding="utf-8")
    print(f"wrote crosswalk.md and catalogues.json ({sum(len(c['items']) for c in catalogues)} items)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
